namespace ESPressio::Logging {

    namespace Detail {

        /// Respect the existing EDP-BoundedTypes owners and their per-value
        /// compile-time capacities, rather than accepting unbounded strings.
        template<class TValue>
        struct IsBoundedDiagnosticString final : std::false_type {};

        template<std::size_t TCapacity, class TByteOperations>
        struct IsBoundedDiagnosticString<
            ESPressio::Bounded::String<TCapacity, TByteOperations>
        > final : std::true_type {};

        template<class TValue>
        struct IsBoundedDiagnosticBytes final : std::false_type {};

        template<std::size_t TCapacity, class TByteOperations>
        struct IsBoundedDiagnosticBytes<
            ESPressio::Bounded::Bytes<TCapacity, TByteOperations>
        > final : std::true_type {};

        /// Exact ClockEra certification is activated only by importing the
        /// optional logging/DiagnosticClockEraArguments.hpp adapter header.
        /// The default diagnostic adapter never imports EDP-Clock's concrete
        /// coordinator or activates a new mandatory dependency.
        template<class TValue>
        struct IsCertifiedDiagnosticClockEra final : std::false_type {};

        /// Resolve a fixed-width native scalar to the exact parameter-kind
        /// enum generated by EDP-Localisation, without defining another enum.
        ///
        /// Supported initial profile: fixed arithmetic scalars. Bounded text,
        /// byte and strong semantic types require generated owner-certified
        /// type adapters; they are intentionally NOT guessed or coerced here.
        template<class TKind, class TValue>
        consteval TKind DiagnosticArgumentKindFor() {
            using Value = std::remove_cv_t<TValue>;
            if constexpr (std::is_same_v<Value, bool>) return TKind::Boolean;
            else if constexpr (std::is_same_v<Value, std::int8_t>) return TKind::Signed8;
            else if constexpr (std::is_same_v<Value, std::int16_t>) return TKind::Signed16;
            else if constexpr (std::is_same_v<Value, std::int32_t>) return TKind::Signed32;
            else if constexpr (std::is_same_v<Value, std::int64_t>) return TKind::Signed64;
            else if constexpr (std::is_same_v<Value, std::uint8_t>) return TKind::Unsigned8;
            else if constexpr (std::is_same_v<Value, std::uint16_t>) return TKind::Unsigned16;
            else if constexpr (std::is_same_v<Value, std::uint32_t>) return TKind::Unsigned32;
            else if constexpr (std::is_same_v<Value, std::uint64_t>) return TKind::Unsigned64;
            else if constexpr (std::is_same_v<Value, float>) return TKind::Float32;
            else if constexpr (std::is_same_v<Value, double>) return TKind::Float64;
            else if constexpr (IsBoundedDiagnosticString<Value>::value) return TKind::Utf8;
            else if constexpr (IsBoundedDiagnosticBytes<Value>::value) return TKind::Bytes;
            else if constexpr (std::is_same_v<Value, ESPressio::System::TypeIdentifier>)
                return TKind::TypeIdentifier;
            else if constexpr (std::is_same_v<Value, ESPressio::System::FieldIdentifier>)
                return TKind::FieldIdentifier;
            else if constexpr (std::is_same_v<Value, ESPressio::System::Identity::DeviceIdentifier>)
                return TKind::DeviceIdentifier;
            else if constexpr (std::is_same_v<Value, ESPressio::System::Identity::RuntimeIncarnationId>)
                return TKind::RuntimeIncarnationId;
            else if constexpr (IsCertifiedDiagnosticClockEra<Value>::value)
                return TKind::ClockEra;
            else {
                static_assert(
                    std::is_same_v<Value, void>,
                    "Logging G3 diagnostic adapter: unsupported argument Type; owner-certified canonical representation required"
                );
            }
        }
    }


    /// Proves bounded arguments and exact strong semantic identifiers against
    /// one EDP-Localisation
    /// GENERATED DiagnosticMessageSchema descriptor. Never substitutes
    /// a hand-written TypeId or a run-time parameter registry.
    template<class TGeneratedMessageSchema, class... TValues>
    consteval bool DiagnosticSchemaMatches() {
        using KindArray = std::remove_cv_t<decltype(TGeneratedMessageSchema::ArgumentKinds)>;
        using Kind = typename KindArray::value_type;
        if constexpr (
            !TGeneratedMessageSchema::Declared ||
            TGeneratedMessageSchema::ArgumentCount != sizeof...(TValues)
        ) {
            return false;
        } else {
            return TGeneratedMessageSchema::ArgumentKinds ==
                std::array<Kind, sizeof...(TValues)>{
                    Detail::DiagnosticArgumentKindFor<Kind, TValues>()...
                };
        }
    }

    /// Source-compatible alias for previous scalar-only instrumentation.
    /// New callers can use DiagnosticSchemaMatches for owner-certified
    /// bounded UTF-8, Bytes and strong System identifiers as well.
    template<class TGeneratedMessageSchema, class... TValues>
    consteval bool ScalarDiagnosticSchemaMatches() {
        return DiagnosticSchemaMatches<TGeneratedMessageSchema, TValues...>();
    }

    /// Strict compile-time governed scalar positional CBOR encoder. Caller
    /// owns complete destination and handles the typed Serialisation result.
    /// This is ONLY the Field13 positional value, not a LogRecord envelope.
    template<class TGeneratedMessageSchema, class... TValues>
    [[nodiscard]] ESPressio::Serialisation::SerialisationResult EncodeDiagnosticArgumentsCbor(
        std::span<std::byte> destination,
        const TValues&... values
    ) noexcept {
        static_assert(
            DiagnosticSchemaMatches<TGeneratedMessageSchema, TValues...>(),
            "Diagnostic argument types/widths/count do not match the EDP-Localisation generated message schema"
        );
        static_assert(
            (ESPressio::Serialisation::SerialisableType<TValues> && ...),
            "Diagnostic input must have EDP-Serialisation owner-certified C++ value support"
        );
        return ESPressio::Serialisation::SerialisePositionalCbor<
            TGeneratedMessageSchema::ArgumentCount
        >(destination, values...);
    }

    /// Strict governed scalar positional JSON encoder, still not an outer
    /// Typed Envelope. All JSON canonicalisation belongs to EDP-Serialisation.
    template<class TGeneratedMessageSchema, class... TValues>
    [[nodiscard]] ESPressio::Serialisation::SerialisationResult EncodeDiagnosticArgumentsJson(
        std::span<std::byte> destination,
        const TValues&... values
    ) noexcept {
        static_assert(
            DiagnosticSchemaMatches<TGeneratedMessageSchema, TValues...>(),
            "Diagnostic argument types/widths/count do not match the EDP-Localisation generated message schema"
        );
        static_assert(
            (ESPressio::Serialisation::SerialisableType<TValues> && ...),
            "Diagnostic input must have EDP-Serialisation owner-certified C++ value support"
        );
        return ESPressio::Serialisation::SerialisePositionalJson<
            TGeneratedMessageSchema::ArgumentCount
        >(destination, values...);
    }

} // namespace ESPressio::Logging
